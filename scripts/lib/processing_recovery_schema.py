        "REQUEST_COUNT INTEGER NOT NULL CHECK(REQUEST_COUNT BETWEEN 0 AND 1000000), STEP_COUNT INTEGER NOT NULL CHECK(STEP_COUNT BETWEEN 0 AND 1000000), "
        "TOKEN_COUNT INTEGER NOT NULL CHECK(TOKEN_COUNT BETWEEN 0 AND 1000000000), PROGRESS_DIGEST VARCHAR(64), "
        "CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, UNIQUE(BUDGET_ID,ACTION_KEY), UNIQUE(BUDGET_ID,ACTION_NO))",
        "CREATE TABLE CX_PROCESSING_BLOCKS (BLOCK_ID VARCHAR(128) PRIMARY KEY, BUDGET_ID VARCHAR(128) NOT NULL REFERENCES CX_PROCESSING_BUDGETS(BUDGET_ID), "
        "CONTINUITY_ID VARCHAR(128) NOT NULL REFERENCES CX_PROCESSING_CHAINS(CONTINUITY_ID), "
        "ATTEMPT_ID VARCHAR(128) REFERENCES CX_TASK_CONTINUITY_ATTEMPTS(ATTEMPT_ID), "
        "OBSERVATION_KEY VARCHAR(128) NOT NULL, OBSERVATION_DIGEST VARCHAR(64) NOT NULL, "
