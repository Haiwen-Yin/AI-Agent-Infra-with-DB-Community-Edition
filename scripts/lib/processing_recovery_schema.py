        "CONTINUITY_ID VARCHAR(128) NOT NULL REFERENCES CX_PROCESSING_CHAINS(CONTINUITY_ID), "
        "ATTEMPT_ID VARCHAR(128) NOT NULL REFERENCES CX_TASK_CONTINUITY_ATTEMPTS(ATTEMPT_ID), "
