        "CREATE TABLE CX_PROCESSING_NATIVE_ATTEMPTS (EXECUTION_ID VARCHAR(128) NOT NULL REFERENCES CX_RUNTIME_EXECUTIONS(EXECUTION_ID), "
        "NATIVE_FENCING_TOKEN INTEGER NOT NULL CHECK(NATIVE_FENCING_TOKEN>0), "
        "CONTINUITY_ID VARCHAR(128) NOT NULL REFERENCES CX_PROCESSING_CHAINS(CONTINUITY_ID), "
        "TASK_ATTEMPT_ID VARCHAR(128) NOT NULL UNIQUE REFERENCES CX_TASK_CONTINUITY_ATTEMPTS(ATTEMPT_ID), "
        "WORKER_ID VARCHAR(128) NOT NULL, NODE_ID VARCHAR(128) NOT NULL, "
        "PRIMARY KEY(EXECUTION_ID,NATIVE_FENCING_TOKEN))",
        "CREATE TABLE CX_PROCESSING_NATIVE_CALLS (SOURCE_ATTEMPT_ID VARCHAR(128) PRIMARY KEY, "
        "TASK_ATTEMPT_ID VARCHAR(128) NOT NULL REFERENCES CX_PROCESSING_NATIVE_ATTEMPTS(TASK_ATTEMPT_ID), "
        "PROVIDER_NO INTEGER NOT NULL CHECK(PROVIDER_NO BETWEEN 1 AND 1000000), "
        "SOURCE_KIND VARCHAR(16) NOT NULL CHECK(SOURCE_KIND IN ('NATIVE','CHANNEL')), INPUT_DIGEST VARCHAR(64) NOT NULL, "
        "UNIQUE(TASK_ATTEMPT_ID,PROVIDER_NO))",
        "CREATE INDEX CX_PROCESSING_BLOCK_CHAIN ON CX_PROCESSING_BLOCKS(CONTINUITY_ID,STATUS)",
        "CREATE INDEX CX_PROCESSING_ACTION_SIG ON CX_PROCESSING_ACTIONS(BUDGET_ID,ACTION_SIGNATURE)",
