        "SOURCE_FAMILY VARCHAR(24), SOURCE_ID VARCHAR(128), SOURCE_REVISION_ID VARCHAR(128), SOURCE_DIGEST VARCHAR(64), "
        "CHECK((SOURCE_FAMILY IS NULL AND SOURCE_ID IS NULL AND SOURCE_REVISION_ID IS NULL AND SOURCE_DIGEST IS NULL) OR "
