        "CREATE TABLE CX_PROCESSING_NATIVE_AGENTS (AGENT_ID VARCHAR(64) PRIMARY KEY REFERENCES AGENT_REGISTRY(AGENT_ID), "
        "NATIVE_AGENT_ID VARCHAR(128) NOT NULL UNIQUE REFERENCES CX_NATIVE_AGENTS(AGENT_ID), REGISTRY_DIGEST VARCHAR(64) NOT NULL, "
        "CHECK(AGENT_ID=NATIVE_AGENT_ID))",
        "CREATE TABLE CX_PROCESSING_BUDGETS (BUDGET_ID VARCHAR(128) PRIMARY KEY, "
        "ROOT_CONTINUITY_ID VARCHAR(128) NOT NULL UNIQUE REFERENCES CX_TASK_CONTINUITY_LINKS(CONTINUITY_ID), "
