        "TOKENS_USED INTEGER DEFAULT 0 NOT NULL CHECK(TOKENS_USED>=0), NO_PROGRESS_COUNT INTEGER DEFAULT 0 NOT NULL CHECK(NO_PROGRESS_COUNT>=0), "
        "LAST_PROGRESS_DIGEST VARCHAR(64), VERSION INTEGER DEFAULT 1 NOT NULL CHECK(VERSION>0), "
        "CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)",
        "CREATE TABLE CX_PROCESSING_CHAINS (CONTINUITY_ID VARCHAR(128) PRIMARY KEY REFERENCES CX_TASK_CONTINUITY_LINKS(CONTINUITY_ID), "
        "BUDGET_ID VARCHAR(128) NOT NULL REFERENCES CX_PROCESSING_BUDGETS(BUDGET_ID), "
        "ORIGINAL_CONTINUITY_ID VARCHAR(128) NOT NULL REFERENCES CX_TASK_CONTINUITY_LINKS(CONTINUITY_ID), "
        "CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)",
        "CREATE TABLE CX_PROCESSING_TARGETS (CONTINUITY_ID VARCHAR(128) PRIMARY KEY REFERENCES CX_PROCESSING_CHAINS(CONTINUITY_ID), "
        "TARGET_KIND VARCHAR(24) NOT NULL CHECK(TARGET_KIND IN ('RUNTIME','GRAPH','LOOP','TASK_STEP','PROTOCOL')), "
