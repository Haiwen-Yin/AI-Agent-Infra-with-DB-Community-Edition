        "SOURCE_FAMILY VARCHAR(24), SOURCE_ID VARCHAR(128), SOURCE_REVISION_ID VARCHAR(128), SOURCE_DIGEST VARCHAR(64), "
        "BUSINESS_KEY VARCHAR(256) NOT NULL, REASON_CODE VARCHAR(64) NOT NULL, "
        "CATEGORY VARCHAR(16) NOT NULL CHECK(CATEGORY IN ('BLOCKED','DEGRADED','UNKNOWN')), "
        "RETRIEVAL_PATH VARCHAR(24) NOT NULL CHECK(RETRIEVAL_PATH IN ('NOT_APPLICABLE','SEMANTIC','TEXTUAL','HYBRID','UNAVAILABLE')), "
        "MATCH_STATE VARCHAR(16) NOT NULL CHECK(MATCH_STATE IN ('NOT_APPLICABLE','MATCHED','EMPTY','UNKNOWN')), "
        "POLICY_DIGEST VARCHAR(64) NOT NULL, REQUESTS_USED INTEGER NOT NULL CHECK(REQUESTS_USED>=0), STEPS_USED INTEGER NOT NULL CHECK(STEPS_USED>=0), "
        "TOKENS_USED INTEGER NOT NULL CHECK(TOKENS_USED>=0), STATUS VARCHAR(24) NOT NULL CHECK(STATUS IN ('OPEN','RECOVERY_ACCEPTED','RESOLVED')), "
