"""Additive, typed coordinator state. Never applied at service startup."""
from . import model_coordinator_schema

# Only progress fields are mutable. Generators deny direct Agent SQL and
# enforce the complement with native immutable-column triggers.
MUTABLE = {
    "CX_MODEL_CAP_GROUPS": {"CURRENT_REVISION", "NEXT_SEQUENCE", "VERSION", "STATUS"},
    "CX_MODEL_CAP_ORIGINS": {"STATUS", "VERSION"},
    "CX_MODEL_ADMISSIONS": {"STATUS", "VERSION", "FENCING_TOKEN", "LEASE_UNTIL_MS", "CANCEL_STATE", "FINISH_CODE"},
    "CX_MODEL_CAP_ATTEMPTS": {"STATUS", "FINISH_CODE", "COMPLETED_AT_MS"},
    "CX_RUNTIME_MODEL_CREDENTIALS": set(),
}
MUTABLE.update(model_coordinator_schema.MUTABLE)


def schema_statements(dialect):
    if dialect not in {"oracle", "pg", "postgresql", "yashandb"}:
        raise ValueError("Unsupported database adapter")
    statements = [
        "CREATE TABLE CX_MODEL_CAP_GROUPS (GROUP_ID VARCHAR(128) PRIMARY KEY, RESOURCE_KEY VARCHAR(128) NOT NULL UNIQUE, "
        "COORDINATOR_ID VARCHAR(128) NOT NULL, CURRENT_REVISION INTEGER NOT NULL CHECK(CURRENT_REVISION>0), "
        "NEXT_SEQUENCE INTEGER DEFAULT 1 NOT NULL CHECK(NEXT_SEQUENCE>0), VERSION INTEGER DEFAULT 1 NOT NULL CHECK(VERSION>0), "
        "STATUS VARCHAR(24) NOT NULL CHECK(STATUS IN ('ACTIVE','DRAINING')), "
        "CREATED_BY VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), CREATED_AT_MS NUMERIC(19,0) NOT NULL)",
        "CREATE TABLE CX_MODEL_CAP_REVISIONS (GROUP_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_CAP_GROUPS(GROUP_ID), "
        "REVISION_NO INTEGER NOT NULL CHECK(REVISION_NO>0), CAPACITY INTEGER NOT NULL CHECK(CAPACITY BETWEEN 1 AND 16), "
        "QUEUE_MS INTEGER NOT NULL CHECK(QUEUE_MS BETWEEN 0 AND 3600000), SOCKET_MS INTEGER NOT NULL CHECK(SOCKET_MS BETWEEN 1000 AND 600000), "
        "IDLE_MS INTEGER NOT NULL CHECK(IDLE_MS BETWEEN 1000 AND 600000), OVERALL_MS INTEGER NOT NULL CHECK(OVERALL_MS BETWEEN 1000 AND 7200000), "
        "RESERVATION_MS INTEGER NOT NULL CHECK(RESERVATION_MS BETWEEN 1000 AND 120000), "
        "CREATED_BY VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), REASON VARCHAR(1000) NOT NULL, CREATED_AT_MS NUMERIC(19,0) NOT NULL, "
        "PRIMARY KEY(GROUP_ID,REVISION_NO), CHECK(QUEUE_MS<OVERALL_MS), CHECK(RESERVATION_MS<=OVERALL_MS))",
        "CREATE TABLE CX_MODEL_CAP_ORIGINS (GROUP_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_CAP_GROUPS(GROUP_ID), "
        "ORIGIN_ID VARCHAR(128) NOT NULL, PRINCIPAL_ID VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), "
        "INSTALLATION_KEY VARCHAR(128) NOT NULL, STATUS VARCHAR(24) NOT NULL CHECK(STATUS IN ('ACTIVE','REVOKED')), "
        "VERSION INTEGER DEFAULT 1 NOT NULL CHECK(VERSION>0), REGISTERED_BY VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), "
        "CREATED_AT_MS NUMERIC(19,0) NOT NULL, PRIMARY KEY(GROUP_ID,ORIGIN_ID))",
        "CREATE TABLE CX_MODEL_CAP_ALIASES (ALIAS_KEY VARCHAR(64) PRIMARY KEY, ENDPOINT_URL VARCHAR(1000) NOT NULL, "
        "GROUP_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_CAP_GROUPS(GROUP_ID), "
        "REGISTERED_BY VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), CREATED_AT_MS NUMERIC(19,0) NOT NULL)",
        "CREATE TABLE CX_MODEL_CAP_BINDINGS (PROFILE_ID VARCHAR(128) PRIMARY KEY REFERENCES CX_LLM_PROVIDER_PROFILES(PROFILE_ID), "
        "GROUP_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_CAP_GROUPS(GROUP_ID), "
        "REGISTERED_BY VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), CREATED_AT_MS NUMERIC(19,0) NOT NULL)",
        "CREATE TABLE CX_MODEL_ADMISSIONS (ADMISSION_ID VARCHAR(128) PRIMARY KEY, "
        "GROUP_ID VARCHAR(128) NOT NULL, POLICY_REVISION INTEGER NOT NULL, ORIGIN_ID VARCHAR(128) NOT NULL, "
        "ACTOR_ID VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), "
        "PROFILE_ID VARCHAR(128) NOT NULL REFERENCES CX_LLM_PROVIDER_PROFILES(PROFILE_ID), PROFILE_VERSION INTEGER NOT NULL CHECK(PROFILE_VERSION>0), "
        "MODEL_ID VARCHAR(256) NOT NULL, ALIAS_KEY VARCHAR(64) NOT NULL REFERENCES CX_MODEL_CAP_ALIASES(ALIAS_KEY), "
        "INPUT_DIGEST VARCHAR(64) NOT NULL, CREDENTIAL_DIGEST VARCHAR(64) NOT NULL, REQUEST_DIGEST VARCHAR(64) NOT NULL, "
        "SOURCE_KIND VARCHAR(24) NOT NULL CHECK(SOURCE_KIND IN ('NATIVE','GATEWAY','PORTAL','CHANNEL','PROBE','RETROSPECTIVE','EVALUATION','EXTERNAL')), "
        "SOURCE_ID VARCHAR(128) NOT NULL, SOURCE_ATTEMPT_ID VARCHAR(128) NOT NULL, QUEUE_SEQUENCE INTEGER NOT NULL CHECK(QUEUE_SEQUENCE>0), "
        "STATUS VARCHAR(24) NOT NULL CHECK(STATUS IN ('QUEUED','RESERVED','DISPATCHING','UNKNOWN','COMPLETED','REJECTED','CANCELLED','EXPIRED')), "
        "VERSION INTEGER DEFAULT 1 NOT NULL CHECK(VERSION>0), FENCING_TOKEN INTEGER DEFAULT 0 NOT NULL CHECK(FENCING_TOKEN>=0), "
        "LEASE_UNTIL_MS NUMERIC(19,0), QUEUE_UNTIL_MS NUMERIC(19,0) NOT NULL, OVERALL_UNTIL_MS NUMERIC(19,0) NOT NULL, "
        "CANCEL_STATE VARCHAR(32) NOT NULL CHECK(CANCEL_STATE IN ('NOT_REQUESTED','QUEUE_CANCELLED','LOCAL_CANCELLED','REMOTE_CONFIRMED')), "
        "FINISH_CODE VARCHAR(128), CREATED_AT_MS NUMERIC(19,0) NOT NULL, UNIQUE(GROUP_ID,QUEUE_SEQUENCE), "
        "FOREIGN KEY(GROUP_ID,POLICY_REVISION) REFERENCES CX_MODEL_CAP_REVISIONS(GROUP_ID,REVISION_NO), "
        "FOREIGN KEY(GROUP_ID,ORIGIN_ID) REFERENCES CX_MODEL_CAP_ORIGINS(GROUP_ID,ORIGIN_ID))",
        "CREATE TABLE CX_MODEL_CAP_ATTEMPTS (ATTEMPT_ID VARCHAR(128) PRIMARY KEY, "
        "ADMISSION_ID VARCHAR(128) NOT NULL UNIQUE REFERENCES CX_MODEL_ADMISSIONS(ADMISSION_ID), "
        "FENCING_TOKEN INTEGER NOT NULL CHECK(FENCING_TOKEN>0), WORKER_KEY VARCHAR(128) NOT NULL, "
        "STATUS VARCHAR(24) NOT NULL CHECK(STATUS IN ('DISPATCHING','UNKNOWN','COMPLETED','RECONCILED')), "
        "DISPATCH_AT_MS NUMERIC(19,0) NOT NULL, COMPLETED_AT_MS NUMERIC(19,0), FINISH_CODE VARCHAR(128))",
        "CREATE TABLE CX_MODEL_CAP_EVIDENCE (EVIDENCE_ID VARCHAR(128) PRIMARY KEY, "
        "ADMISSION_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_ADMISSIONS(ADMISSION_ID), "
        "ATTEMPT_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_CAP_ATTEMPTS(ATTEMPT_ID), "
        "ACTOR_ID VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), RESOURCE_VERSION INTEGER NOT NULL CHECK(RESOURCE_VERSION>0), "
        "EVIDENCE_KIND VARCHAR(32) NOT NULL CHECK(EVIDENCE_KIND IN ('COMPLETE_RESPONSE','REMOTE_TERMINATED','LOCAL_LIFECYCLE','OPERATOR_CONFIRMATION','TRANSPORT_UNKNOWN')), "
        "EVIDENCE_DIGEST VARCHAR(64) NOT NULL, FINISH_CODE VARCHAR(128) NOT NULL, REASON VARCHAR(1000) NOT NULL, CREATED_AT_MS NUMERIC(19,0) NOT NULL)",
        "CREATE TABLE CX_MODEL_CAP_REQUESTS (ACTOR_ID VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), "
        "OPERATION VARCHAR(64) NOT NULL, IDEMPOTENCY_KEY VARCHAR(128) NOT NULL, REQUEST_DIGEST VARCHAR(64) NOT NULL, "
        "GROUP_ID VARCHAR(128) NOT NULL REFERENCES CX_MODEL_CAP_GROUPS(GROUP_ID), "
        "ADMISSION_ID VARCHAR(128) REFERENCES CX_MODEL_ADMISSIONS(ADMISSION_ID), RESOURCE_VERSION INTEGER NOT NULL CHECK(RESOURCE_VERSION>0), "
        "CREATED_AT_MS NUMERIC(19,0) NOT NULL, PRIMARY KEY(ACTOR_ID,OPERATION,IDEMPOTENCY_KEY))",
        "CREATE TABLE CX_RUNTIME_MODEL_CREDENTIALS (EXECUTION_ID VARCHAR(128) PRIMARY KEY REFERENCES CX_RUNTIME_EXECUTIONS(EXECUTION_ID), "
        "ACTOR_ID VARCHAR(128) NOT NULL REFERENCES CX_PRINCIPALS(PRINCIPAL_ID), "
        "CREDENTIAL_KIND VARCHAR(8) NOT NULL CHECK(CREDENTIAL_KIND IN ('WEB','AGENT')), CREDENTIAL_DIGEST VARCHAR(64) NOT NULL, "
        "REQUIRED_SCOPE VARCHAR(128), INSTANCE_ID VARCHAR(128), FENCING_TOKEN INTEGER DEFAULT 0 NOT NULL CHECK(FENCING_TOKEN>=0), "
        "AUTH_METHOD VARCHAR(64), PERMISSION_VERSION INTEGER DEFAULT 0 NOT NULL CHECK(PERMISSION_VERSION>=0), "
        "MFA_LEVEL VARCHAR(32), NODE_ID VARCHAR(128), SESSION_CREATED_AT VARCHAR(64), "
        "PROFILE_ID VARCHAR(128) REFERENCES CX_LLM_PROVIDER_PROFILES(PROFILE_ID), PROFILE_VERSION INTEGER CHECK(PROFILE_VERSION>0), "
        "INPUT_DIGEST VARCHAR(64) NOT NULL, EXECUTION_DIGEST VARCHAR(64) NOT NULL, SOURCE_DIGEST VARCHAR(64), "
        "CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, "
        "CHECK((CREDENTIAL_KIND='WEB' AND AUTH_METHOD IS NOT NULL AND PERMISSION_VERSION>0 AND SESSION_CREATED_AT IS NOT NULL) "
        "OR (CREDENTIAL_KIND='AGENT' AND INSTANCE_ID IS NOT NULL AND FENCING_TOKEN>0)))",
        "CREATE TABLE CX_MODEL_RUNTIME_OBSERVATIONS (ADMISSION_ID VARCHAR(128) PRIMARY KEY REFERENCES CX_MODEL_ADMISSIONS(ADMISSION_ID), "
        "ATTEMPT_ID VARCHAR(128) NOT NULL UNIQUE REFERENCES CX_MODEL_CAP_ATTEMPTS(ATTEMPT_ID), "
        "API_DIALECT VARCHAR(24) NOT NULL CHECK(API_DIALECT='CHAT_COMPLETIONS'), "
        "REQUEST_COMPLETE VARCHAR(1) NOT NULL CHECK(REQUEST_COMPLETE IN ('Y','N')), "
        "RESULT_STATE VARCHAR(24) NOT NULL CHECK(RESULT_STATE IN ('COMPLETED','REJECTED','UNKNOWN')), "
        "FINISH_CODE VARCHAR(128) NOT NULL, USAGE_PROVENANCE VARCHAR(24) NOT NULL "
        "CHECK(USAGE_PROVENANCE IN ('PROVIDER_REPORTED','DERIVED_TOTAL','PARTIAL','INCOMPLETE')), "
        "PROMPT_TOKENS NUMERIC(19,0) CHECK(PROMPT_TOKENS>=0), COMPLETION_TOKENS NUMERIC(19,0) CHECK(COMPLETION_TOKENS>=0), "
        "TOTAL_TOKENS NUMERIC(19,0) CHECK(TOTAL_TOKENS>=0), CACHED_TOKENS NUMERIC(19,0) CHECK(CACHED_TOKENS>=0), "
        "CACHE_WRITE_TOKENS NUMERIC(19,0) CHECK(CACHE_WRITE_TOKENS>=0), REASONING_TOKENS NUMERIC(19,0) CHECK(REASONING_TOKENS>=0), "
        "QUEUE_MS NUMERIC(19,0) NOT NULL CHECK(QUEUE_MS>=0), FIRST_CONTENT_MS NUMERIC(19,0) CHECK(FIRST_CONTENT_MS>=0), "
        "PROVIDER_MS NUMERIC(19,0) NOT NULL CHECK(PROVIDER_MS>=0), TOTAL_MS NUMERIC(19,0) NOT NULL CHECK(TOTAL_MS>=0), "
        "OBSERVATION_DIGEST VARCHAR(64) NOT NULL, OBSERVED_AT_MS NUMERIC(19,0) NOT NULL, "
        "CHECK((RESULT_STATE='UNKNOWN' AND REQUEST_COMPLETE='N') OR (RESULT_STATE IN ('COMPLETED','REJECTED') AND REQUEST_COMPLETE='Y')))",
        "CREATE TABLE CX_MODEL_USAGE_DETAILS (USAGE_ID VARCHAR(128) PRIMARY KEY REFERENCES CX_MODEL_USAGE(USAGE_ID), "
        "CACHE_WRITE_TOKENS NUMERIC(19,0) CHECK(CACHE_WRITE_TOKENS>=0), "
        "USAGE_PROVENANCE VARCHAR(24) NOT NULL CHECK(USAGE_PROVENANCE IN ('PROVIDER_REPORTED','DERIVED_TOTAL','PARTIAL','INCOMPLETE')), "
        "CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)",
    ]
    # Match existing native verification's canonical type spellings. Plain
    # PostgreSQL INTEGER cannot hold current epoch milliseconds or int64 usage.
    precise_integer = "DECIMAL(19,0)" if dialect in {"pg", "postgresql"} else "NUMBER(19)"
    statements[-1:-1] = model_coordinator_schema.schema_statements(dialect)
    return [statement.replace("NUMERIC(19,0)", precise_integer) for statement in statements]
