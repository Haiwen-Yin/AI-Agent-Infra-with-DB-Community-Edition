GRANT SELECT ON CX_AGENT_KNOWLEDGE_META_READ TO DEEP_SEC_SESSION_ROLE;
GRANT SELECT ON CX_AGENT_EMBEDDING_READ TO DEEP_SEC_SESSION_ROLE;
GRANT SELECT ON CX_AGENT_EDGE_READ TO DEEP_SEC_SESSION_ROLE;

-- Native writes bind ownership to SESSION_USER. No owner or visibility argument.
CREATE OR REPLACE PACKAGE CX_AGENT_ENTITY_API AS
  PROCEDURE CREATE_PRIVATE(p_id VARCHAR2, p_type VARCHAR2, p_title VARCHAR2, p_content CLOB);
  PROCEDURE UPDATE_PRIVATE(p_id VARCHAR2, p_title VARCHAR2, p_content CLOB);
END;
/
CREATE OR REPLACE PACKAGE BODY CX_AGENT_ENTITY_API AS
  FUNCTION current_agent RETURN VARCHAR2 IS
    a VARCHAR2(128);
  BEGIN
    SELECT i.AGENT_ID INTO a FROM CX_AGENT_DB_IDENTITIES i
      JOIN CX_PRINCIPALS p ON p.PRINCIPAL_ID=i.AGENT_ID AND p.STATUS='ACTIVE'
      WHERE i.DB_USERNAME=SYS_CONTEXT('USERENV','SESSION_USER');
    RETURN a;
  END;
  PROCEDURE CREATE_PRIVATE(p_id VARCHAR2, p_type VARCHAR2, p_title VARCHAR2, p_content CLOB) IS
    a VARCHAR2(128);
  BEGIN
    a:=current_agent();
    IF p_type IS NULL OR p_type NOT IN ('MEMORY','KNOWLEDGE') THEN
      RAISE_APPLICATION_ERROR(-20001,'unsupported entity type');
    END IF;
    INSERT INTO ENTITIES(ENTITY_ID,ENTITY_TYPE,TITLE,CONTENT,OWNED_BY_AGENT,SOURCE_AGENT,VISIBILITY)
      VALUES(p_id,p_type,p_title,p_content,a,a,'PRIVATE');
    IF p_type='KNOWLEDGE' THEN
      INSERT INTO KNOWLEDGE_META(ENTITY_ID,ENTITY_TYPE) VALUES(p_id,p_type);
    END IF;
  END;
  PROCEDURE UPDATE_PRIVATE(p_id VARCHAR2, p_title VARCHAR2, p_content CLOB) IS
    a VARCHAR2(128);
  BEGIN
    a:=current_agent();
    UPDATE ENTITIES SET TITLE=p_title,CONTENT=p_content,UPDATED_AT=CURRENT_TIMESTAMP
      WHERE ENTITY_ID=p_id AND OWNED_BY_AGENT=a AND VISIBILITY='PRIVATE'
      AND ENTITY_TYPE IN ('MEMORY','KNOWLEDGE')
      AND NOT EXISTS (SELECT 1 FROM CX_KNOWLEDGE_ACCESS_POLICIES k WHERE k.ENTITY_ID=p_id);
    IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20002,'entity unavailable'); END IF;
  END;
END;
/
GRANT EXECUTE ON CX_AGENT_ENTITY_API TO DEEP_SEC_SESSION_ROLE;
